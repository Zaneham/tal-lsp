#!/usr/bin/env python3
"""Exemplar and robustness tests for tal-lspd.

Opens every file under exemplar/ and requires it to come back clean,
then hammers hover, completion and definition at every position, then
fuzzes the server with mutated and hostile inputs and requires it to
keep answering.

    python3 test_exemplar.py [server] [--fuzz N] [--seed S] [--quick]

    This test was generated by Claude - ZH
"""

import subprocess, json, sys, os, random, time, tempfile

opts = sys.argv[1:]
args = [a for i, a in enumerate(opts) if not a.startswith('--') and (i == 0 or not opts[i - 1].startswith('--'))]
fuzz_n = int(opts[opts.index('--fuzz') + 1]) if '--fuzz' in opts else 400
seed = int(opts[opts.index('--seed') + 1]) if '--seed' in opts else 2026
quick = '--quick' in opts
here = os.path.dirname(os.path.abspath(__file__))
server = args[0] if args else os.path.join(here, 'tal-lspd.exe' if os.name == 'nt' else 'tal-lspd')
exdir = os.path.join(here, 'exemplar')
crash_dir = os.path.join(here, 'fuzz-crashes')

proc = None
errf = None
fails = []
requests = 0

def start():
    global proc, errf
    if proc is not None and proc.poll() is None:
        proc.kill()
    errf = tempfile.TemporaryFile()
    proc = subprocess.Popen([server], stdin=subprocess.PIPE,
                            stdout=subprocess.PIPE, stderr=errf)
    send({'jsonrpc': '2.0', 'id': 1, 'method': 'initialize',
          'params': {'capabilities': {}, 'rootUri': None}})
    recv()
    send({'jsonrpc': '2.0', 'method': 'initialized', 'params': {}})

def send(msg):
    global requests
    requests += 1
    data = json.dumps(msg).encode()
    proc.stdin.write(f'Content-Length: {len(data)}\r\n\r\n'.encode() + data)
    proc.stdin.flush()

def recv():
    line = b''
    while True:
        c = proc.stdout.read(1)
        if not c:
            return None
        line += c
        if line.endswith(b'\r\n\r\n'):
            break
    length = int(line.split(b':')[1].strip().split(b'\r')[0])
    body = proc.stdout.read(length)
    try:
        return json.loads(body)
    except ValueError:
        print(f'  [FAIL] malformed response ({length} bytes)')
        fails.append('malformed response')
        return None

def check(name, cond, detail=''):
    if not cond:
        fails.append(name)
    print(f"  [{'PASS' if cond else 'FAIL'}] {name}" + (f'  {detail}' if detail and not cond else ''))

def lang_of(name):
    ext = os.path.splitext(name)[1].lower()
    if ext == '.tacl': return 'tacl'
    if ext == '.ptal': return 'ptal'
    if ext == '.tal': return 'tal'
    return 'tacl'

def open_doc(uri, lang, text):
    send({'jsonrpc': '2.0', 'method': 'textDocument/didOpen', 'params': {
        'textDocument': {'uri': uri, 'languageId': lang, 'version': 1, 'text': text}}})
    r = recv()
    return None if r is None else r['params']['diagnostics']

def change_doc(uri, ver, text):
    send({'jsonrpc': '2.0', 'method': 'textDocument/didChange', 'params': {
        'textDocument': {'uri': uri, 'version': ver}, 'contentChanges': [{'text': text}]}})
    r = recv()
    return None if r is None else r['params']['diagnostics']

def close_doc(uri):
    send({'jsonrpc': '2.0', 'method': 'textDocument/didClose',
          'params': {'textDocument': {'uri': uri}}})
    recv()

rid = 100
def req(method, uri, line=None, char=None):
    global rid
    rid += 1
    p = {'textDocument': {'uri': uri}}
    if line is not None:
        p['position'] = {'line': line, 'character': char}
    send({'jsonrpc': '2.0', 'id': rid, 'method': method, 'params': p})
    r = recv()
    if r is None:
        return None
    return r if r.get('id') == rid else recv()

def sev(d):
    return {1: 'error', 2: 'warning', 3: 'info', 4: 'hint'}.get(d.get('severity'), '?')

outline = {
    'hello.tal': ['term^len', 'term^name', 'msg', 'hello'],
    'server.tal': ['max^msg', 'request^def', 'request', 'reply^buf', 'requests',
                   'bump', 'is^urgent', 'sum^words', 'send^reply', 'server'],
    'ledger.tal': ['txn^def', 'txns', 'balance', 'n^txns', 'post', 'show^balance', 'ledger'],
    'ringbuf.ptal': ['ring^def', 'ring', 'remote', 'ring^init', 'ring^put', 'ring^get', 'ring^main'],
    'toolkit.tacl': ['banner', 'greet', 'cf', 'job^rec', 'countdown', 'spin'],
}

# ---- Exemplars ----
start()
print('--- Exemplars ---')
files = sorted(f for f in os.listdir(exdir) if os.path.isfile(os.path.join(exdir, f)))
texts = {}
for f in files:
    text = open(os.path.join(exdir, f), encoding='utf-8').read()
    texts[f] = text
    uri = 'file:///exemplar/' + f
    d = open_doc(uri, lang_of(f), text)
    for x in d:
        print(f"      {f}:{x['range']['start']['line'] + 1}: {sev(x)}: {x['message']}")
    check(f'{f} ({lang_of(f)}) is clean', d is not None and len(d) == 0)

    r = req('textDocument/documentSymbol', uri)
    syms = r.get('result') or []
    names = [s['name'].lower() for s in syms]
    want = outline.get(f)
    if want:
        missing = [w for w in want if w.lower() not in names]
        check(f'{f} outline has {", ".join(want)}', not missing, f'missing {missing}')

    lines = text.split('\n')
    alive = True
    hovers = defs = comps = 0
    for ln, s in enumerate(lines):
        if quick:
            break
        for col in range(len(s) + 1):
            if 0 < col < len(s) and s[col] != ' ' and s[col - 1] != ' ':
                continue
            for m in ('textDocument/hover', 'textDocument/definition', 'textDocument/completion'):
                r = req(m, uri, ln, col)
                if r is None:
                    alive = False
                    break
                if r.get('result'):
                    if m.endswith('hover'): hovers += 1
                    elif m.endswith('definition'): defs += 1
                    else: comps += 1
            if not alive:
                break
        if not alive:
            break
    if not quick:
        check(f'{f} survives every word edge', alive)
        check(f'{f} answers hover somewhere', hovers > 0)
        check(f'{f} answers completion somewhere', comps > 0)
    if alive:
        close_doc(uri)
    else:
        start()

# ---- Fuzz ----
print()
print(f'--- Fuzz ({fuzz_n} rounds, seed {seed}) ---')
rng = random.Random(seed)
junk = '[]{}|~"\'#?%&<>:=.^$!()@;,\\-+*/\n\t'
words = ['#IF', '#LOOP', '|THEN|', '|DO|', '|UNTIL|', '?TACL', '?SECTION', '#FRAME',
         'PROC', 'BEGIN', 'END', 'STRUCT', 'DEFINE', '#;', "':='", "'+'", '->',
         '.<0:15>', '$LEN', 'CASE', 'OF', 'OTHERWISE', 'INT(32)', 'FIXED(2)',
         '%1%', '~;', '==', '{', '}', '&', 'CODE(', 'WADDR', 'LITERAL']

def mutate(text):
    n = rng.randint(1, 6)
    for _ in range(n):
        k = rng.randint(0, 9)
        if not text:
            text = rng.choice(words)
            continue
        a = rng.randint(0, len(text) - 1)
        b = min(len(text), a + rng.randint(1, 40))
        if k == 0: text = text[:a] + text[b:]
        elif k == 1: text = text[:a] + text[a:b] + text[a:b] + text[b:]
        elif k == 2: text = text[:a] + rng.choice(junk) + text[a:]
        elif k == 3: text = text[:a] + rng.choice(words) + text[a:]
        elif k == 4: text = text[:a]
        elif k == 5: text = text[:a] + ''.join(rng.choice(junk) for _ in range(rng.randint(1, 30))) + text[b:]
        elif k == 6: text = text[:a] + text[a:b].upper() + text[b:]
        elif k == 7: text = text[:a] + ''.join(chr(rng.randint(0x80, 0x10ffff)) for _ in range(3)) + text[a:]
        elif k == 8: text = text[:a] + text[a:b] * rng.randint(2, 20) + text[b:]
        else: text = text[:a] + '\n' * rng.randint(1, 5) + text[a:]
    return text

def hostile():
    return [
        ('300 nested [', '?TACL MACRO\n' + '[' * 300 + ']' * 300 + '\n'),
        ('300 nested BEGIN', 'PROC p MAIN;\n' + 'BEGIN\n' * 300 + 'END;\n' * 300),
        ('300 nested parens', 'INT x := ' + '(' * 300 + '1' + ')' * 300 + ';\n'),
        ('6000 char line', '?TACL MACRO\n' + '#OUTPUT ' + 'x' * 6000 + '\n'),
        ('30000 lines', 'INT a;\n' * 30000),
        ('only bars', '|' * 2000),
        ('only quotes', '"' * 2001),
        ('only tildes', '?TACL MACRO\n' + '~' * 2000),
        ('only hashes', '#' * 2000),
        ('only dollars', '$' * 2000),
        ('only carets', 'INT ' + '^' * 2000 + ';'),
        ('only percent', '?TACL MACRO\n' + '%' * 2001),
        ('unterminated string', 'STRING s := "abc\n' * 100),
        ('unterminated comment', '?TACL MACRO\n{ never closes\n' * 100),
        ('deep dotref', 'INT x := a' + '.b' * 500 + ';'),
        ('deep subscript', 'INT x := a' + '[1]' * 500 + ';'),
        ('long ident', 'INT ' + 'a' * 5000 + ';'),
        ('long number', 'INT x := ' + '9' * 5000 + ';'),
        ('long hex', 'INT x := %H' + 'F' * 5000 + ';'),
        ('nul bytes', 'INT a;\x00\x00\x00PROC p;\x00'),
        ('crlf tal', 'PROC p MAIN;\r\nBEGIN\r\nINT a;\r\na := 1;\r\nEND;\r\n'),
        ('crlf tacl', '?TACL MACRO\r\n#FRAME\r\n#OUTPUT hi &\r\n  there\r\n#UNFRAME\r\n'),
        ('empty', ''),
        ('one newline', '\n'),
        ('define forever', 'DEFINE d = ' + 'x ' * 3000),
        ('case forever', 'PROC p; BEGIN CASE x OF BEGIN ' + '1 -> a; ' * 2000 + 'END; END;'),
        ('call 500 args', 'PROC p; BEGIN CALL q(' + 'a, ' * 500 + 'a); END;'),
        ('tacl 100 labels', '?TACL MACRO\n[#CASE x ' + ''.join(f'|{i}| a\n' for i in range(100)) + ']'),
        ('tacl 2000 pushes', '?TACL MACRO\n#PUSH ' + ' '.join(f'v{i}' for i in range(2000)) + '\n'),
        ('tacl 3000 sections', ''.join(f'?SECTION s{i} MACRO\n#OUTPUT {i}\n' for i in range(3000))),
        ('tal 3000 procs', ''.join(f'PROC p{i}; BEGIN INT a{i}; a{i} := {i}; END;\n' for i in range(3000))),
        ('every byte', ''.join(chr(i) for i in range(1, 256)) * 8),
    ]

crashes = 0
rounds = 0
t0 = time.time()

def probe(uri, text, label, lang):
    global crashes
    ver = rng.randint(2, 1 << 30)
    d = change_doc(uri, ver, text)
    ok = d is not None
    if ok:
        lines = text.split('\n')
        for _ in range(3):
            ln = rng.randint(0, max(0, len(lines) - 1))
            col = rng.randint(0, max(0, len(lines[ln]) if ln < len(lines) else 0))
            m = rng.choice(['textDocument/hover', 'textDocument/completion',
                            'textDocument/definition', 'textDocument/documentSymbol'])
            r = req(m, uri, ln, col) if m != 'textDocument/documentSymbol' else req(m, uri)
            if r is None:
                ok = False
                break
    if not ok:
        crashes += 1
        errf.seek(0)
        err = errf.read().decode(errors='replace')[-2000:]
        os.makedirs(crash_dir, exist_ok=True)
        path = os.path.join(crash_dir, f'crash-{crashes:03d}-{lang}.txt')
        with open(path, 'w', encoding='utf-8', newline='') as fh:
            fh.write(text)
        print(f'  [FAIL] server died on {label} -> {path}')
        if err.strip():
            print('        ' + err.strip().replace('\n', '\n        '))
        start()
        open_doc(uri, lang, '')
    return ok

for lang, base in (('tal', 'fuzz.tal'), ('ptal', 'fuzz.ptal'), ('tacl', 'fuzz.tacl')):
    uri = 'file:///fuzz/' + base
    open_doc(uri, lang, '')
    for label, text in hostile():
        rounds += 1
        probe(uri, text, f'{lang}: {label}', lang)
    pool = [t for f, t in texts.items() if lang_of(f) == lang]
    for i in range(fuzz_n):
        rounds += 1
        text = mutate(rng.choice(pool))
        probe(uri, text, f'{lang} mutation {i}', lang)
    close_doc(uri)

check(f'{rounds} fuzz rounds, server never died', crashes == 0, f'{crashes} crashes')

send({'jsonrpc': '2.0', 'id': 9999, 'method': 'shutdown', 'params': None})
recv()
send({'jsonrpc': '2.0', 'method': 'exit', 'params': None})
try:
    proc.wait(timeout=5)
except subprocess.TimeoutExpired:
    proc.kill()

print()
print(f'{requests} requests in {time.time() - t0:.1f}s')
if fails:
    print(f'{len(fails)} FAILED:')
    for f in fails:
        print('  ' + f)
    sys.exit(1)
print('ALL CHECKS PASSED')
