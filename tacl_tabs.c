/* ---- Lookup ---- */

static const tc_ent_t *find(const tc_ent_t *t, uint32_t n, const char *s, uint32_t len)
{
    for (uint32_t i = 0; i < n; i++) {
        const char *nm = t[i].name;
        uint32_t k = 0;
        while (k < len && nm[k] &&
               toupper((unsigned char)s[k]) == (unsigned char)nm[k])
            k++;
        if (k == len && nm[k] == '\0') return &t[i];
    }
    return NULL;
}

const tc_ent_t *tc_bfind(const char *s, uint32_t len)
{
    if (!s || len == 0 || len > TAL_MAX_IDENT) return NULL;
    return find(tc_bltab, tc_nbl, s, len);
}

const tc_ent_t *tc_cfind(const char *s, uint32_t len)
{
    if (!s || len == 0 || len > TAL_MAX_IDENT) return NULL;
    return find(tc_cmtab, tc_ncm, s, len);
}
